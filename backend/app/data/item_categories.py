"""
物品分類定義 - 集中管理物品類別
"""

# ============================================================
# 工具類物品
# ============================================================

TOOLS = {
    "hoe",       # 鋤頭
    "pickaxe",   # 鶴嘴鋤
    "axe",       # 斧頭
    "shears",    # 剪刀
    "cleaver",   # 屠刀
    "hammer",    # 鐵鎚
    "saw",       # 鋸子
    "scraper",   # 刮刀
}


# ============================================================
# 食物類物品
# ============================================================

FOODS = {
    "bread",        # 麵包
    "meat_raw",     # 生肉
    "meat",         # 熟肉
}


# ============================================================
# 原料類物品
# ============================================================

RAW_MATERIALS = {
    # L1 原料
    "grain",    # 穀物
    "ore",      # 鐵礦
    "wood",     # 木材
    "wool",     # 羊毛
    
    # L2 原料
    "flour",    # 麵粉
    "iron",     # 鐵錠
    "hide",     # 羊皮
    "cloth",    # 布料
    "leather",  # 皮革
}


# ============================================================
# 成品類物品
# ============================================================

PRODUCTS = {
    "bread",      # 麵包
    "meat_raw",   # 生肉（屠夫產品）
    "furniture",  # 家具
    "clothes",    # 衣服
}


# ============================================================
# 輔助函數
# ============================================================

def is_tool(item_id: str) -> bool:
    """判斷是否為工具"""
    return item_id in TOOLS


def is_food(item_id: str) -> bool:
    """判斷是否為食物"""
    return item_id in FOODS


def is_raw_material(item_id: str) -> bool:
    """判斷是否為原料"""
    return item_id in RAW_MATERIALS


def get_drop_priority(item_id: str) -> int:
    """取得丟棄優先級（數字越大越先丟）
    
    優先級：原料 > 工具 > 食物（食物不丟）
    """
    if item_id in RAW_MATERIALS:
        return 3  # 最先丟
    if item_id in TOOLS:
        return 2
    if item_id in FOODS:
        return 0  # 不丟食物
    return 1  # 其他
